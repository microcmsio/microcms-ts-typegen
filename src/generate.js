const IDENTIFIER = /^[$A-Z_a-z][$\w]*$/;
const RESERVED = new Set(['break', 'case', 'class', 'const', 'default', 'delete', 'do', 'else', 'enum', 'export', 'extends', 'false', 'finally', 'for', 'function', 'if', 'import', 'in', 'instanceof', 'interface', 'let', 'new', 'null', 'return', 'static', 'super', 'switch', 'this', 'throw', 'true', 'try', 'typeof', 'var', 'void', 'while', 'with', 'yield']);
export const GENERATED_HEADER = '// This file is generated by microcms-typegen. Do not edit by hand.';

export function pascalCase(value) {
  const parts = value.match(/[\p{L}\p{N}]+/gu) ?? [];
  const name = parts.map((part) => part[0].toUpperCase() + part.slice(1)).join('');
  if (!name) throw new Error(`Cannot make a type name from ${JSON.stringify(value)}`);
  return /^\d/.test(name) ? `_${name}` : name;
}

function typeName(value) {
  if (typeof value !== 'string' || !IDENTIFIER.test(value) || RESERVED.has(value)) {
    throw new Error(`Invalid TypeScript type name: ${JSON.stringify(value)}`);
  }
  return value;
}

function propertyName(name) {
  if (typeof name !== 'string' || !name) throw new Error('A schema field is missing fieldId');
  return IDENTIFIER.test(name) ? name : JSON.stringify(name);
}

function union(types) {
  return [...new Set(types)].join(' | ');
}

const nullable = new Set(['text', 'textArea', 'richEditorV2', 'number', 'relation', 'custom', 'repeater']);
const omittable = new Set(['text', 'textArea', 'richEditorV2', 'richEditor', 'media', 'file', 'date', 'number', 'iframe']);

export function generateTypes(apis, schemas, { extensionFieldTypes = {}, serviceName } = {}) {
  const names = new Map();
  const used = new Map([
    ['MicroCMSImage', 'built-in image type'],
    ['MicroCMSFile', 'built-in file type'],
  ]);
  function registerPublicName(name, source) {
    if (used.has(name)) {
      throw new Error(`Type name collision: ${JSON.stringify(name)} is used by ${used.get(name)} and ${source}`);
    }
    used.set(name, source);
  }
  for (const api of apis) {
    const name = typeName(pascalCase(api.endpoint));
    registerPublicName(name, `endpoint ${JSON.stringify(api.endpoint)}`);
    names.set(api.endpoint, name);
  }
  const customNames = new Map();
  for (const api of apis) {
    const schema = schemas.get(api.endpoint);
    if (!schema) throw new Error(`Missing schema for ${api.endpoint}`);
    const namesForApi = new Map();
    for (const item of schema.customFields) {
      if (namesForApi.has(item.fieldId)) throw new Error(`Duplicate custom field in ${api.endpoint}`);
      const name = typeName(`${names.get(api.endpoint)}CustomField${pascalCase(item.fieldId)}`);
      registerPublicName(name, `custom field ${JSON.stringify(`${api.endpoint}.${item.fieldId}`)}`);
      namesForApi.set(item.fieldId, name);
    }
    customNames.set(api.endpoint, namesForApi);
  }

  const serviceSchemaName = typeName(serviceName === undefined
    ? 'MainServiceSchema'
    : `${pascalCase(serviceName)}ServiceSchema`);
  registerPublicName(serviceSchemaName, `service schema ${JSON.stringify(serviceName ?? 'main')}`);

  function internalName(base) {
    let name = base;
    for (let suffix = 2; used.has(name); suffix++) name = `${base}${suffix}`;
    used.set(name, 'internal helper type');
    return name;
  }
  const expandName = internalName('__MicroCMSTypegenExpand');
  const extensionWriteName = internalName('__MicroCMSTypegenExtensionFieldWrite');
  const readNames = new Map();
  const createNames = new Map();
  const updateNames = new Map();
  const customReadNames = new Map();
  const customCreateNames = new Map();
  const customUpdateNames = new Map();
  for (const api of apis) {
    readNames.set(api.endpoint, internalName(`__MicroCMSTypegen${names.get(api.endpoint)}Read`));
    createNames.set(api.endpoint, internalName(`__MicroCMSTypegen${names.get(api.endpoint)}Create`));
    updateNames.set(api.endpoint, internalName(`__MicroCMSTypegen${names.get(api.endpoint)}Update`));
    const readForApi = new Map();
    const createForApi = new Map();
    const updateForApi = new Map();
    for (const [fieldId, name] of customNames.get(api.endpoint)) {
      readForApi.set(fieldId, internalName(`__MicroCMSTypegen${name}Read`));
      createForApi.set(fieldId, internalName(`__MicroCMSTypegen${name}Create`));
      updateForApi.set(fieldId, internalName(`__MicroCMSTypegen${name}Update`));
    }
    customReadNames.set(api.endpoint, readForApi);
    customCreateNames.set(api.endpoint, createForApi);
    customUpdateNames.set(api.endpoint, updateForApi);
  }
  if (extensionFieldTypes === null || typeof extensionFieldTypes !== 'object' || Array.isArray(extensionFieldTypes)) {
    throw new Error('extensionFieldTypes must be an object');
  }
  const extensionDataTypes = new Map();
  const externalImports = [];
  for (const [endpoint, fieldOverrides] of Object.entries(extensionFieldTypes)) {
    const schema = schemas.get(endpoint);
    if (!names.has(endpoint) || !schema) throw new Error(`Unknown extensionFieldTypes endpoint ${endpoint}`);
    if (fieldOverrides === null || typeof fieldOverrides !== 'object' || Array.isArray(fieldOverrides)) {
      throw new Error(`extensionFieldTypes.${endpoint} must be an object`);
    }
    const availableFields = new Map(schema.apiFields.map((field) => [field.fieldId, field]));
    const ambiguousPaths = new Set();
    for (const customField of schema.customFields) {
      for (const field of customField.fields) {
        const path = `${customField.fieldId}.${field.fieldId}`;
        if (availableFields.has(path)) ambiguousPaths.add(path);
        availableFields.set(path, field);
      }
    }
    const forEndpoint = new Map();
    for (const [path, override] of Object.entries(fieldOverrides)) {
      if (ambiguousPaths.has(path)) throw new Error(`Ambiguous extension field path ${endpoint}.${path}`);
      if (availableFields.get(path)?.kind !== 'iframe') {
        throw new Error(`extensionFieldTypes.${endpoint}.${path} must name an extension field`);
      }
      if (override === null || typeof override !== 'object' || Array.isArray(override)) {
        throw new Error(`extensionFieldTypes.${endpoint}.${path} must be an object`);
      }
      const unexpected = Object.keys(override).filter((key) => !['from', 'data'].includes(key));
      if (unexpected.length) throw new Error(`Unknown extensionFieldTypes.${endpoint}.${path} option ${unexpected[0]}`);
      if (typeof override.from !== 'string' || !override.from.trim()
        || typeof override.data !== 'string' || !override.data.trim()) {
        throw new Error(`extensionFieldTypes.${endpoint}.${path} needs nonempty from and data strings`);
      }
      const importedName = typeName(override.data);
      const alias = internalName(`__MicroCMSTypegen${names.get(endpoint)}${pascalCase(path)}Data`);
      externalImports.push(`import type { ${importedName} as ${alias} } from ${JSON.stringify(override.from.trim())};`);
      forEndpoint.set(path, alias);
    }
    extensionDataTypes.set(endpoint, forEndpoint);
  }
  function fieldPaths(endpoint, relationDepth = 3) {
    const schema = schemas.get(endpoint);
    const api = apis.find((item) => item.endpoint === endpoint);
    if (!schema || !api) throw new Error(`Missing schema for ${endpoint}`);
    const paths = new Set(api.type === 'list'
      ? ['id', 'createdAt', 'updatedAt', 'publishedAt', 'revisedAt']
      : ['createdAt', 'updatedAt', 'publishedAt', 'revisedAt']);
    for (const field of schema.apiFields) {
      paths.add(field.fieldId);
      if (relationDepth > 0 && (field.kind === 'relation' || field.kind === 'relationList')) {
        for (const child of fieldPaths(field.referencedApiEndpoint, relationDepth - 1)) {
          paths.add(`${field.fieldId}.${child}`);
        }
      } else if (field.kind === 'relation' || field.kind === 'relationList') {
        // A reference at the expansion boundary still contains its content ID.
        paths.add(`${field.fieldId}.id`);
      }
    }
    return paths;
  }

  function renderApi(api) {
    const schema = schemas.get(api.endpoint);
    if (!schema) throw new Error(`Missing schema for ${api.endpoint}`);
    const custom = customNames.get(api.endpoint);
    const declarations = [];

    function selectType(field) {
      if (!Array.isArray(field.selectItems) || field.selectItems.some((item) => typeof item?.value !== 'string')) {
        throw new Error(`Invalid selectItems in ${api.endpoint}.${field.fieldId}`);
      }
      const values = field.selectItems.map((item) => JSON.stringify(item.value));
      return `(${values.length ? union(values) : 'never'})[]`;
    }

    function repeaterIds(field) {
      if (!Array.isArray(field.customFieldIds) || field.customFieldIds.some((id) => typeof id !== 'string' || !id)) {
        throw new Error(`Invalid customFieldIds in ${api.endpoint}.${field.fieldId}`);
      }
      return field.customFieldIds;
    }

    function fieldType(field, prefix) {
      switch (field.kind) {
        case 'text': case 'textArea': case 'richEditorV2': case 'richEditor': case 'date': return 'string';
        case 'number': return 'number';
        case 'boolean': return 'boolean';
        case 'media': return 'MicroCMSImage';
        case 'mediaList': return 'MicroCMSImage[]';
        case 'file': return 'MicroCMSFile';
        case 'select': return selectType(field);
        case 'relation': case 'relationList': {
          const name = readNames.get(field.referencedApiEndpoint);
          if (!name) throw new Error(`Relation target ${JSON.stringify(field.referencedApiEndpoint)} in ${api.endpoint}.${field.fieldId} was not found`);
          const reference = `(__MicroCMSTypegenResolveDepth<Options> extends 0 ? { id: string } : ${name}<__MicroCMSTypegenReferenceOptions<Options>>)`;
          return field.kind === 'relationList' ? `${reference}[]` : reference;
        }
        // Extension data can be any JSON value, including empty strings, null, and arrays.
        case 'iframe': return extensionDataTypes.get(api.endpoint)?.get(`${prefix}${field.fieldId}`) ?? 'unknown';
        case 'custom': {
          const name = customReadNames.get(api.endpoint).get(field.customFieldId);
          if (!name) throw new Error(`Unknown custom field ${JSON.stringify(field.customFieldId)} in ${api.endpoint}.${field.fieldId}`);
          return `${name}<Options>`;
        }
        case 'repeater': {
          const variants = repeaterIds(field).map((id) => {
            const name = customReadNames.get(api.endpoint).get(id);
            if (!name) throw new Error(`Unknown repeat field ${JSON.stringify(id)} in ${api.endpoint}.${field.fieldId}`);
            return `${name}<Options>`;
          });
          return `(${union(variants.length ? variants : ['never'])})[]`;
        }
        default: throw new Error(`Unsupported field kind ${JSON.stringify(field.kind)} in ${api.endpoint}.${field.fieldId}`);
      }
    }

    function renderFields(fields, { optionalAll = false, prefix = '' } = {}) {
      if (!Array.isArray(fields)) throw new Error(`Invalid field list for ${api.endpoint}`);
      const seen = new Set();
      return fields.map((field) => {
        if (seen.has(field.fieldId)) throw new Error(`Duplicate field ${field.fieldId} in ${api.endpoint}`);
        seen.add(field.fieldId);
        const optional = optionalAll || omittable.has(field.kind) ? '?' : '';
        const base = fieldType(field, prefix);
        const type = nullable.has(field.kind) ? `${base} | null` : base;
        return `  ${propertyName(field.fieldId)}${optional}: ${type};`;
      });
    }

    function writeFieldType(field, mode, prefix) {
      switch (field.kind) {
        case 'text': case 'textArea': case 'richEditorV2': case 'richEditor': case 'date':
        case 'media': case 'file': case 'relation':
          return field.kind === 'relation' && mode === 'update'
            ? 'string | Record<string, never>' : 'string';
        case 'number': return mode === 'update' ? 'number | null' : 'number';
        case 'boolean': return mode === 'update' ? 'boolean | null' : 'boolean';
        case 'mediaList': case 'relationList': return 'string[]';
        case 'select': return selectType(field);
        case 'iframe': {
          const dataType = extensionDataTypes.get(api.endpoint)?.get(`${prefix}${field.fieldId}`);
          return dataType ? `${extensionWriteName}<${dataType}>` : 'Record<string, unknown>';
        }
        case 'custom': {
          const name = (mode === 'create' ? customCreateNames : customUpdateNames)
            .get(api.endpoint).get(field.customFieldId);
          if (!name) throw new Error(`Unknown custom field ${JSON.stringify(field.customFieldId)} in ${api.endpoint}.${field.fieldId}`);
          return mode === 'update' ? `${name} | Record<string, never>` : name;
        }
        case 'repeater': {
          const namesForApi = (mode === 'create' ? customCreateNames : customUpdateNames).get(api.endpoint);
          const variants = repeaterIds(field).map((id) => {
            const name = namesForApi.get(id);
            if (!name) throw new Error(`Unknown repeat field ${JSON.stringify(id)} in ${api.endpoint}.${field.fieldId}`);
            return name;
          });
          return `(${union(variants.length ? variants : ['never'])})[]`;
        }
        default: throw new Error(`Unsupported field kind ${JSON.stringify(field.kind)} in ${api.endpoint}.${field.fieldId}`);
      }
    }

    function renderWriteFields(fields, mode, prefix = '') {
      return fields.map((field) => `  ${propertyName(field.fieldId)}?: ${writeFieldType(field, mode, prefix)};`);
    }

    for (const item of schema.customFields) {
      const readName = customReadNames.get(api.endpoint).get(item.fieldId);
      declarations.push(`type ${readName}<Options extends __MicroCMSTypegenReadOptions = {}> = {\n  fieldId: ${JSON.stringify(item.fieldId)};\n${renderFields(item.fields, { optionalAll: true, prefix: `${item.fieldId}.` }).join('\n')}\n};`);
      declarations.push(`export type ${custom.get(item.fieldId)} = ${readName}<{}>;`);
      for (const mode of ['create', 'update']) {
        const name = (mode === 'create' ? customCreateNames : customUpdateNames)
          .get(api.endpoint).get(item.fieldId);
        declarations.push(`type ${name} = {\n  fieldId: ${JSON.stringify(item.fieldId)};\n${renderWriteFields(item.fields, mode, `${item.fieldId}.`).join('\n')}\n};`);
      }
    }
    const metadata = api.type === 'list'
      ? ['  id: string;', '  createdAt: string;', '  updatedAt: string;', '  publishedAt?: string;', '  revisedAt?: string;']
      : api.type === 'object'
        ? ['  createdAt: string;', '  updatedAt: string;', '  publishedAt?: string;', '  revisedAt?: string;']
        : null;
    if (!metadata) throw new Error(`Unsupported API type ${JSON.stringify(api.type)} for ${api.endpoint}`);
    const metadataFieldIds = new Set(metadata.map((line) => line.trim().split(/[?:]/, 1)[0]));
    const schemaFields = renderFields(schema.apiFields).filter((_, index) =>
      !metadataFieldIds.has(schema.apiFields[index].fieldId));
    declarations.push(`type ${readNames.get(api.endpoint)}<Options extends __MicroCMSTypegenReadOptions = {}> = {\n${[...metadata, ...schemaFields].join('\n')}\n};`);
    declarations.push(`export type ${names.get(api.endpoint)} = ${readNames.get(api.endpoint)}<{}>;`);
    const writeFields = schema.apiFields.filter((field) => !metadataFieldIds.has(field.fieldId));
    if (api.type === 'list') {
      declarations.push(`type ${createNames.get(api.endpoint)} = {\n${['  publishedAt?: string;', ...renderWriteFields(writeFields, 'create')].join('\n')}\n};`);
    }
    declarations.push(`type ${updateNames.get(api.endpoint)} = {\n${['  publishedAt?: string;', ...renderWriteFields(writeFields, 'update')].join('\n')}\n};`);
    return declarations.join('\n\n');
  }

  const body = apis.map(renderApi).join('\n\n');
  const schemaEntries = apis.map((api) => {
    const name = names.get(api.endpoint);
    const readName = readNames.get(api.endpoint);
    const depths = [0, 1, 2, 3].map((depth) => `${depth}: ${readName}<{ depth: ${depth} }>`).join('; ');
    const paths = [...fieldPaths(api.endpoint)].map((path) => JSON.stringify(path)).join(' | ');
    const create = api.type === 'list' ? `create: ${expandName}<${createNames.get(api.endpoint)}>; ` : '';
    return `  ${JSON.stringify(api.endpoint)}: { kind: ${JSON.stringify(api.type)}; content: ${name}; depths: { ${depths} }; fieldPaths: ${paths}; ${create}update: ${expandName}<${updateNames.get(api.endpoint)}> };`;
  });
  const serviceSchema = `export type ${serviceSchemaName} = {\n${schemaEntries.join('\n')}\n};`;
  const expand = `type ${expandName}<Value> = Value extends readonly unknown[]\n  ? { [Key in keyof Value]: ${expandName}<Value[Key]> }\n  : Value extends Record<string, unknown>\n    ? { [Key in keyof Value]: ${expandName}<Value[Key]> }\n    : Value;`;
  const extensionWrite = externalImports.length
    ? `type ${extensionWriteName}<Data> = {\n  id?: string;\n  title?: string;\n  description?: string;\n  imageUrl?: string;\n  updatedAt?: string;\n  data?: Data;\n};\n`
    : '';
  return `${GENERATED_HEADER}\n\n${externalImports.length ? `${externalImports.join('\n')}\n\n` : ''}type __MicroCMSTypegenDepth = 0 | 1 | 2 | 3;\ntype __MicroCMSTypegenReadOptions = { depth?: __MicroCMSTypegenDepth };\ntype __MicroCMSTypegenPreviousDepth = { 0: 0; 1: 0; 2: 1; 3: 2 };\ntype __MicroCMSTypegenResolveDepth<Options extends __MicroCMSTypegenReadOptions> = Options extends { depth: infer Depth } ? Depth extends __MicroCMSTypegenDepth ? Depth : 1 : 1;\ntype __MicroCMSTypegenReferenceOptions<Options extends __MicroCMSTypegenReadOptions> = Omit<Options, 'depth'> & { depth: __MicroCMSTypegenPreviousDepth[__MicroCMSTypegenResolveDepth<Options>] };\n${expand}\n${extensionWrite}\nexport type MicroCMSImage = { url: string; width?: number; height?: number; alt?: string };\nexport type MicroCMSFile = { url: string; fileSize: number };\n\n${body}\n\n${serviceSchema}\n`;
}

export async function collectSchemas(client, selectedEndpoints, options) {
  const allApis = await client.listApis();
  const byEndpoint = new Map(allApis.map((api) => [api.endpoint, api]));
  const queue = selectedEndpoints?.length ? [...selectedEndpoints] : allApis.map((api) => api.endpoint);
  const schemas = new Map();
  for (let index = 0; index < queue.length; index++) {
    const endpoint = queue[index];
    if (!byEndpoint.has(endpoint)) throw new Error(`Endpoint ${endpoint} was not found in this service`);
    if (schemas.has(endpoint)) continue;
    const schema = await client.getSchema(endpoint);
    schemas.set(endpoint, schema);
    const fields = [
      ...schema.apiFields.map((field) => ({ field, location: `${endpoint}.${field.fieldId}` })),
      ...schema.customFields.flatMap((item) => item.fields.map((field) => ({ field, location: `${endpoint}.${item.fieldId}.${field.fieldId}` }))),
    ];
    for (const { field, location } of fields) {
      if (field.kind !== 'relation' && field.kind !== 'relationList') continue;
      const target = field.referencedApiEndpoint;
      if (typeof target !== 'string' || !byEndpoint.has(target)) {
        const selectionHint = selectedEndpoints?.length
          ? ''
          : ' To generate other APIs while this is unresolved, specify them in the config endpoints array.';
        throw new Error(`Relation target ${JSON.stringify(target)} in ${location} was not found in this service. Check the referenced API setting for this field in the microCMS management screen.${selectionHint}`);
      }
      queue.push(target);
    }
  }
  const apis = allApis.filter((api) => schemas.has(api.endpoint));
  return generateTypes(apis, schemas, options);
}
